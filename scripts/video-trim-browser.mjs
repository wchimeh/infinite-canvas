import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { requireQaSession } from './qa-session.mjs';
const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const { url, dataDir } = await requireQaSession();
const fixture = path.join(dataDir, 'video-trim-qa.mp4');
execFileSync(path.join(process.env.FFMPEG_DIR, 'ffmpeg.exe'), ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=128x128:r=25', '-f', 'lavfi', '-i', 'sine=frequency=440', '-t', '4', '-c:v', 'libx264', '-c:a', 'aac', fixture], { windowsHide: true });
const bytes = (await readFile(fixture)).toString('base64');
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(url); await expect(page.locator('.app-shell')).toBeVisible();
  await page.evaluate(async bytes => {
    const opts = (method, body) => ({ method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const p = await (await fetch('/api/v1/projects', opts('POST', { name: 'Video trim QA' }))).json();
    const form = new FormData(); form.set('projectId', p.id); form.set('file', new Blob([Uint8Array.from(atob(bytes), c => c.charCodeAt(0))], { type: 'video/mp4' }), 'source.mp4');
    const asset = await (await fetch('/api/v1/assets/import', { method: 'POST', body: form })).json();
    const c = await (await fetch(`/api/v1/canvases/${p.id}`)).json();
    c.nodes = [{ id: 'source', type: 'studio', position: { x: 0, y: 0 }, data: { kind: 'asset.video', title: 'Source', config: { assetId: asset.id } } },
      { id: 'trim', type: 'studio', position: { x: 350, y: 0 }, data: { kind: 'video.trim', title: 'Trim QA', config: {} } }];
    c.edges = [{ id: 'video', source: 'source', target: 'trim', sourceHandle: 'video', targetHandle: 'video' }];
    const req = opts('PUT', c); req.headers['If-Match'] = String(c.version);
    if (!(await fetch(`/api/v1/canvases/${p.id}`, req)).ok) throw new Error('fixture save failed');
    localStorage.setItem('canvas-last-project', p.id);
  }, bytes);
  await page.reload();
  await expect(page.getByRole('button', { name: '视频裁剪', exact: true })).toBeVisible();
  await page.locator('[data-id="trim"] header').click();
  const field = name => page.locator('.inspector').getByLabel(name, { exact: true });
  for (const name of ['生成服务', '提示词', '画面风格']) await expect(field(name)).toHaveCount(0);
  await expect(page.locator('.inspector .reference-list')).toHaveCount(0);
  await expect(field('开始时间（秒）')).toHaveValue('0');
  await expect(field('结束时间（秒）')).toHaveValue('');
  await field('开始时间（秒）').fill('1.2'); await field('结束时间（秒）').fill('1');
  const run = page.locator('.inspector').getByRole('button', { name: '裁剪视频', exact: true });
  await expect(run).toBeDisabled();
  await field('结束时间（秒）').fill('3.2');
  await expect(page.getByText('截取时长：2 秒', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByText('项目已保存', { exact: true })).toBeVisible();
  await page.reload(); await page.locator('[data-id="trim"] header').click();
  await expect(field('开始时间（秒）')).toHaveValue('1.2');
  await expect(field('结束时间（秒）')).toHaveValue('3.2');
  await run.click();
  const video = page.locator('[data-id="trim"] video');
  await expect(video).toBeVisible({ timeout: 20000 });
  await expect.poll(() => video.evaluate(v => v.duration)).toBeCloseTo(2, 1);
  await video.evaluate(v => v.play());
  await expect.poll(() => video.evaluate(v => v.currentTime)).toBeGreaterThan(0);
  await video.evaluate(v => v.pause());
  await expect(page.locator('.inspector').getByRole('button', { name: '重新裁剪', exact: true })).toBeVisible();
  await mkdir('.runtime/qa', { recursive: true });
  await page.screenshot({ path: '.runtime/qa/video-trim.png' });
  expect(errors).toEqual([]);
  console.log('PASS: video trim node, range validation, persistence, local execution, playable two-second video');
} finally { await browser.close(); }
