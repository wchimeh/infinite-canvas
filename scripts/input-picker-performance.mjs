import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { requireQaSession } from './qa-session.mjs';
const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const { url } = await requireQaSession();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(url); await expect(page.locator('.app-shell')).toBeVisible();
  await page.evaluate(async () => {
    const json = (method, body) => ({ method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const project = await (await fetch('/api/v1/projects', json('POST', { name: '1000 candidate performance' }))).json();
    const canvas = await (await fetch(`/api/v1/canvases/${project.id}`)).json();
    const node = (id, kind, x) => ({ id, type: 'studio', position: { x, y: 50 }, data: { kind, title: id, config: {} } });
    canvas.nodes = [node('target', 'image.generate', 450), ...Array.from({ length: 1000 }, (_, i) => node(`素材-${String(i).padStart(4, '0')}`, 'asset.image', -4000))];
    canvas.edges = []; canvas.viewport = { x: 0, y: 0, zoom: 1 };
    const req = json('PUT', canvas); req.headers['If-Match'] = String(canvas.version);
    if (!(await fetch(`/api/v1/canvases/${project.id}`, req)).ok) throw new Error('fixture failed');
    localStorage.setItem('canvas-last-project', project.id);
  });
  await (await page.context().newCDPSession(page)).send('Emulation.setCPUThrottlingRate', { rate: 4 });
  await page.reload();
  const handle = page.locator('[data-id="target"] .target[data-handleid="image"]');
  await expect(handle).toBeVisible({ timeout: 30000 });
  const started = Date.now(); await handle.hover();
  const panel = page.locator('.input-port-picker'); await expect(panel).toBeVisible({ timeout: 10000 });
  const openMs = Date.now() - started;
  await expect(panel).toContainText('1000 个来源');
  const domRows = await panel.locator('.input-picker-option').count();
  expect(domRows).toBeLessThanOrEqual(12);
  const searchStart = Date.now();
  await panel.getByRole('textbox').fill('素材-0999');
  await expect(panel.locator('.input-picker-option')).toHaveCount(1);
  await expect(panel.getByRole('button', { name: '连接：素材-0999', exact: true })).toBeVisible();
  const searchMs = Date.now() - searchStart;
  await panel.getByRole('textbox').fill('');
  await expect(panel.locator('.input-picker-option').first()).toHaveAttribute('aria-label', '连接：素材-0000');
  const list = panel.locator('.input-picker-list');
  await list.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await expect(panel.getByRole('button', { name: '连接：素材-0999', exact: true })).toBeVisible();
  await panel.getByRole('button', { name: '连接：素材-0999', exact: true }).focus();
  await page.keyboard.press('Home');
  await expect(panel.getByRole('button', { name: '连接：素材-0000', exact: true })).toBeFocused();
  await page.keyboard.press('End');
  await expect(panel.getByRole('button', { name: '连接：素材-0999', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowUp');
  await expect(panel.getByRole('button', { name: '连接：素材-0998', exact: true })).toBeFocused();
  await page.keyboard.press('Enter'); await expect(panel).toHaveCount(0);
  await expect(page.locator('.canvas-toolbar .muted')).toContainText('1 连线');
  expect(errors).toEqual([]);
  const report = { candidates: 1000, cpuRate: 4, domRows, openMs, searchMs, errors, note: '本机 CPU 降速模拟，含悬停延迟及自动化操作开销，不代表实体低配置电脑。' };
  await mkdir('.runtime/qa', { recursive: true });
  await writeFile('.runtime/qa/input-picker-performance.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
