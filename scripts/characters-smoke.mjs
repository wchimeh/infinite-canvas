import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const { url } = JSON.parse(await readFile(process.env.CANVAS_SESSION_FILE || new URL('../.runtime/session.json', import.meta.url), 'utf8'));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [], generations = [];
  let activeTasks = [];
  page.on('pageerror', error => errors.push(error.message));
  const characters = [{ name: '小林', description: '年轻创业者', appearance: '短发', wardrobe: '白衬衫', restrictions: '不要帽子' }, { name: '老周', description: '导师', appearance: '灰发', wardrobe: '深色外套', restrictions: '' }];
  let canvas = { nodes: [{ id: 'extract', type: 'studio', selected: true, position: { x: 100, y: 100 }, data: { kind: 'character.extract', title: '提取角色', config: { prompt: '小林创业，老周指导。' } } }], edges: [], viewport: { x: 0, y: 0, zoom: 1 }, version: 1 };
  let people = { characters: [], locations: [], shots: [], version: 1 };
  await page.route('**/api/v1/**', async route => {
    const path = new URL(route.request().url()).pathname, method = route.request().method();
    if (path.endsWith('/session')) return route.continue();
    if (method !== 'GET') {
      const value = route.request().postDataJSON() || {};
      if (path.endsWith('/runs/estimate')) return route.fulfill({ json: { quotes: [], totals: {}, unknownCount: 0, nodeIds: value.nodeIds } });
      if (path.endsWith('/runs')) { generations.push(value); return route.fulfill({ json: { id: 'qa-batch' } }); }
      if (path.includes('/canvases/')) canvas = { ...value, version: canvas.version + 1 };
      if (path.endsWith('/people')) people = { ...value, version: people.version + 1 };
      return route.fulfill({ json: path.includes('/canvases/') ? canvas : path.endsWith('/people') ? people : value });
    }
    if (path.endsWith('/definitions')) {
      const response = await route.fetch(); const defs = await response.json();
      return route.fulfill({ json: { ...defs, 'character.extract': { displayName: '提取角色', inputs: { text: 'text' }, outputs: { text: 'text' } }, 'image.character': { displayName: '生成角色图', inputs: { text: 'text', image: 'image' }, outputs: { image: 'image' } } } });
    }
    if (path.endsWith('/generation-options')) {
      const response = await route.fetch(); const options = await response.json();
      options.workflows.find(w => w.id === 'builtin-image2').kinds.push('image.character');
      return route.fulfill({ json: options });
    }
    if (path.includes('/canvases/')) return route.fulfill({ json: canvas });
    if (path.endsWith('/runs/qa-batch')) return route.fulfill({ json: { tasks: [] } });
    if (path.endsWith('/people')) return route.fulfill({ json: people });
    const imageNode = canvas.nodes.find(n => n.data.kind === 'image.character');
    const asset = { id: 'qa-role-image', name: '角色图.png', mime: 'image/png', nodeId: imageNode?.id, sha256: '12345678', createdAt: 1 };
    if (path.endsWith('/assets')) return route.fulfill({ json: imageNode ? [asset] : [] });
    if (path.includes('/assets/qa-role-image/')) return route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
    if (path.endsWith('/tasks')) return route.fulfill({ json: [...activeTasks, { id: 'qa-characters', node_id: 'extract', run_id: 'qa', status: 'completed', created_at: 1, snapshot: { kind: 'character.extract', config: canvas.nodes[0].data.config }, output: { text: JSON.stringify(characters), characters } }] });
    return route.continue();
  });
  await page.goto(url);
  await expect(page.getByRole('button', { name: '生成角色图', exact: true })).toBeVisible();
  await expect(page.getByLabel('文本服务商')).toBeVisible();
  await expect(page.getByText('角色草案 · 2 人')).toBeVisible();
  await expect(page.getByLabel('批量角色工作流')).toBeVisible();
  await page.getByRole('button', { name: '确认角色并创建形象节点' }).click();
  await expect(page.locator('.profile-card')).toHaveCount(2);
  await expect.poll(() => canvas.nodes.filter(n => n.data.kind === 'image.character').length).toBe(2);
  await expect.poll(() => people.characters.length).toBe(2);
  expect(canvas.nodes.find(n => n.data.title === '小林 · 角色图').data.config.prompt).toContain('不要帽子');
  await page.getByRole('button', { name: /^任务中心/ }).click();
  await page.getByRole('button', { name: '选择节点', exact: true }).click();
  await page.getByRole('button', { name: '确认角色并创建形象节点' }).click();
  await expect(page.locator('.toast')).toContainText('这次任务的角色已确认');
  expect(people.characters.length).toBe(2);
  await page.locator('.react-flow__controls-fitview').click();
  const role = page.locator('.studio-node').filter({ hasText: '小林 · 角色图' });
  await role.locator('header').click();
  await expect(page.getByLabel('生成工作流')).toBeVisible();
  await page.getByLabel('生成工作流').selectOption('builtin-image2');
  await expect(page.locator('.candidate')).toHaveCount(1);
  await page.locator('.candidate').getByRole('button', { name: '采用', exact: true }).click();
  await expect.poll(() => people.characters.find(c => c.name === '小林')?.assetId).toBe('qa-role-image');
  expect(people.characters.find(c => c.name === '老周').assetId).toBeUndefined();
  await page.screenshot({ path: '.runtime/qa/characters-flow.png', fullPage: true });
  expect(generations).toEqual([]);
  const roleIds = canvas.nodes.filter(n => n.data.kind === 'image.character').map(n => n.id).sort();
  await page.getByRole('button', { name: /^任务中心/ }).click();
  await page.getByRole('button', { name: '选择节点', exact: true }).click();
  await page.getByLabel('批量角色工作流').selectOption('builtin-image2');
  await page.getByRole('button', { name: /^生成全部角色/ }).click();
  await expect.poll(() => generations.length).toBe(1);
  expect(generations[0].nodeIds.sort()).toEqual(roleIds);
  expect(canvas.nodes.filter(n => roleIds.includes(n.id)).every(n => n.data.config.workflowId === 'builtin-image2')).toBe(true);
  expect(people.characters.length).toBe(2);
  await expect(page.getByRole('button', { name: /^生成全部角色/ })).toBeEnabled();
  await page.getByRole('button', { name: /^生成全部角色/ }).click();
  await expect.poll(() => generations.length).toBe(2);
  expect(generations[1].nodeIds.sort()).toEqual(roleIds);
  expect(canvas.nodes.filter(n => n.data.kind === 'image.character').length).toBe(2);
  await expect(page.getByRole('button', { name: /^生成全部角色/ })).toBeEnabled();
  canvas.nodes.forEach(n => { n.selected = false; });
  canvas.nodes.push({ id: 'combined', type: 'studio', selected: true, position: { x: 500, y: 100 }, data: { kind: 'image.character', title: '生成角色图', config: { workflowId: 'builtin-image2' } } });
  canvas.edges.push({ id: 'combined-input', source: 'extract', target: 'combined', sourceHandle: 'text', targetHandle: 'text', data: { kind: 'data' } });
  await page.reload();
  await page.getByRole('button', { name: /^生成全部角色/ }).click();
  await expect.poll(() => generations.length).toBe(3);
  expect(generations[2].nodeIds.sort()).toEqual(roleIds);
  expect(canvas.nodes.filter(n => n.data.kind === 'image.character').length).toBe(3);
  await expect(page.getByRole('button', { name: /^生成全部角色/ })).toBeEnabled();
  characters.push(...Array.from({ length: 5 }, (_, i) => ({ name: `新增角色${i + 1}`, description: `独立角色${i + 1}`, appearance: '', wardrobe: '', restrictions: '' })));
  people = { characters: [], locations: [], shots: [], version: people.version + 1 };
  canvas.nodes = canvas.nodes.filter(n => ['extract', 'combined'].includes(n.id));
  canvas.nodes.forEach(node => { node.selected = node.id === 'combined'; });
  await page.reload();
  await expect(page.getByText('7 个角色', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^生成全部角色/ }).click();
  await expect.poll(() => generations.length).toBe(4);
  const independent = canvas.nodes.filter(n => n.data.config.characterId);
  expect(independent.length).toBe(7);
  expect(people.characters.length).toBe(7);
  expect(generations[3].nodeIds.sort()).toEqual(independent.map(n => n.id).sort());
  expect(independent.every(n => n.data.config.workflowId === 'builtin-image2')).toBe(true);
  expect(new Set(independent.map(n => n.data.config.prompt)).size).toBe(7);
  await expect(page.getByRole('region', { name: '角色批量生成' })).toBeVisible();
  await expect(page.getByRole('textbox', { name: '名称', exact: true })).toHaveValue('生成角色图');
  activeTasks = independent.map((node, index) => ({ id: `qa-active-${index}`, node_id: node.id, run_id: 'qa-batch', status: index === 0 ? 'running' : 'queued', created_at: 2, snapshot: { kind: 'image.character', config: node.data.config }, output: {} }));
  canvas.nodes.forEach(node => { node.selected = node.id === 'combined'; });
  await page.reload();
  await expect(page.getByRole('button', { name: '正在生成角色…', exact: true })).toBeDisabled();
  await expect(page.getByText('排队 / 生成中 7', { exact: true })).toBeVisible();
  await expect(page.getByLabel('批量角色工作流')).toBeDisabled();
  expect(generations.length).toBe(4);
  await page.screenshot({ path: '.runtime/qa/characters-batch.png', fullPage: true });
  expect(errors).toEqual([]);
  console.log('PASS: character nodes, text provider, review/import, per-character images, duplicate prevention, workflow and adoption; all writes mocked');
} finally { await browser.close(); }
